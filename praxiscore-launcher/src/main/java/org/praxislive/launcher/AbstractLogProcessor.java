package org.praxislive.launcher;

import java.util.List;
import java.util.Objects;
import org.praxislive.core.Call;
import org.praxislive.core.ComponentAddress;
import org.praxislive.core.Value;
import org.praxislive.core.services.LogLevel;
import org.praxislive.core.services.LogService;
import org.praxislive.core.types.PError;

/**
 * Base support for writing out log messages, for example to the console.
 * Subclasses should implement
 * {@link #write(org.praxislive.core.ComponentAddress, org.praxislive.core.services.LogLevel, java.lang.String)}.
 */
public abstract class AbstractLogProcessor {

    private static final String NEWLINE = System.lineSeparator();

    private LogLevel minLogLevel;

    /**
     * Create an log processor with a default minimum log level of
     * {@link LogLevel#INFO}.
     */
    public AbstractLogProcessor() {
        this.minLogLevel = LogLevel.INFO;
    }

    /**
     * Set the minimum log level to be output by this processor. Log messages
     * below this level will be ignored.
     *
     * @param logLevel minimum log level
     */
    public void setMinimumLevel(LogLevel logLevel) {
        this.minLogLevel = Objects.requireNonNull(logLevel);
    }

    /**
     * Get the minimum log level.
     *
     * @return minimum log level
     */
    public LogLevel getMininumLevel() {
        return minLogLevel;
    }

    /**
     * Process a logging call and write any messages to the implemented output.
     * The call must match the format for {@link LogService}.
     *
     * @param call logging call
     */
    public void processLog(Call call) {
        ComponentAddress src = call.from().component();
        List<Value> args = call.args();
        StringBuilder sb = new StringBuilder();
        LogLevel lastLevel = null;
        for (int i = 1; i < args.size(); i += 2) {
            LogLevel level = LogLevel.valueOf(args.get(i - 1).toString());
            if (!minLogLevel.isLoggable(level)) {
                continue;
            }
            Value arg = args.get(i);
            if (level != lastLevel) {
                lastLevel = level;
                writeHeader(src, level);
            }
            String prefix = generatePrefix(level);
            PError.from(arg).ifPresentOrElse(err -> {
                append(sb, prefix, err.errorType());
                append(sb, prefix, err.message());
                if (level == LogLevel.ERROR) {
                    String stack = err.stackTrace();
                    if (!stack.isBlank()) {
                        append(sb, prefix, stack.indent(4));
                    }
                }
            }, () -> {
                append(sb, prefix, arg.print());
            });
            write(src, level, sb.toString());
            sb.setLength(0);
        }
        flush();
    }

    /**
     * Generate the level and source address header text.
     *
     * @param src source address
     * @param level log level
     * @return header text
     */
    protected String generateHeader(ComponentAddress src, LogLevel level) {
        if (src.rootID().startsWith("_")) {
            return generatePrefix(level) + " === <SYSTEM> ===" + NEWLINE;
        } else {
            return generatePrefix(level) + " === " + src.toString() + " ===" + NEWLINE;
        }
    }

    /**
     * Generate the line prefix.
     *
     * @param level log level
     * @return line prefix
     */
    protected String generatePrefix(LogLevel level) {
        return " [" + level + "] ";
    }

    /**
     * Write the level and source address header. This will be written once for
     * each call, and if any messages within the call have a different level. By
     * default, this method calls
     * {@link #write(org.praxislive.core.ComponentAddress, org.praxislive.core.services.LogLevel, java.lang.String)}
     * with the header generated by
     * {@link #generateHeader(org.praxislive.core.ComponentAddress, org.praxislive.core.services.LogLevel)}
     *
     * @param src source address
     * @param level log level
     */
    protected void writeHeader(ComponentAddress src, LogLevel level) {
        write(src, level, generateHeader(src, level));
    }

    /**
     * Write the text to the destination. Source and log level are provided to
     * assist formatting.
     *
     * @param src source address
     * @param level log level
     * @param text text to write
     */
    protected abstract void write(ComponentAddress src, LogLevel level, String text);

    /**
     * Hook called at the end of processing the log messages to flush any cached
     * output. The default implementation does nothing.
     */
    protected void flush() {
        // no op
    }

    private void append(StringBuilder sb, String prefix, String text) {
        if (prefix.isEmpty()) {
            sb.append(text).append(NEWLINE);
        } else {
            text.lines().forEach(line
                    -> sb.append(prefix).append(line).append(NEWLINE));
        }
    }

}
